    fun everyListedTextIsCopy() {
        assertTrue(texts.size > 500, "only ${texts.size} copy texts found")
        assertTrue(lists.size > 20, "only ${lists.size} enum labels found")
        texts.forEach { (name, read) -> assertTrue(read().isNotBlank(), "$name is blank") }
    }
