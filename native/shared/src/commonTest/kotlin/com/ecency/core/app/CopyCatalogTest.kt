    @Test
    fun copyFollowsALiveLanguageSwitch() {
        // English first, so anything cached would hold English
        texts.forEach { (_, read) -> read() }
        lists.forEach { (_, read) -> read() }
        PseudoLocales.install(PseudoLocales.ACCENTED)
        val english = Regex("[A-Za-z]{2,}")
        val stale = texts.mapNotNull { (name, read) -> read().let { t -> "$name: $t".takeIf { english.containsMatchIn(t) } } } +
            lists.flatMap { (name, read) -> read().filter { english.containsMatchIn(it) }.map { "$name: $it" } }
        assertTrue(stale.isEmpty(), "English after the switch:\n" + stale.joinToString("\n"))
    }

