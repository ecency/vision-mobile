    @Test
    fun reactionGroupsMatchRn() {
        for (case in list("reactions")) {
            val reactions = case["reactions"]!!.jsonArray.mapNotNull { e ->
                val o = e.jsonObject
                // RN skips a reaction without a name; the reader drops it the same way
                ChatReaction.parse(o) ?: return@mapNotNull null
