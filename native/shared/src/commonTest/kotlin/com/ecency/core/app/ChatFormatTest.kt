            assertEquals(expected, ChatGroups.reactions(reactions, "me"))
        }
        val m = list("missing").single()
        assertEquals(m["out"]!!.strings(), ChatGroups.missingUserIds(m["ids"]!!.strings(), m["known"]!!.strings().toSet()))
    }

    @Test
