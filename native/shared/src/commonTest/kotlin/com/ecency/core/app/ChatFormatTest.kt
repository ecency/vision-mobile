            val label = case["channel"].toString()
            assertEquals(case["eligible"]!!.jsonPrimitive.boolean, ChatUnread.eligible(channel), "eligible $label")
            assertEquals(
                ChatUnreadMeta(meta["unreadMentions"]!!.jsonPrimitive.long, meta["unreadMessages"]!!.jsonPrimitive.long, meta["unreadCount"]!!.jsonPrimitive.long, meta["totalUnread"]!!.jsonPrimitive.long),
                ChatUnread.meta(channel), "meta $label",
            )
        }
    }

    @Test
