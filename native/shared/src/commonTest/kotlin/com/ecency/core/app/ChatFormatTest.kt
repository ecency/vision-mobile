    @Test
    fun marksRunThroughMentionsAndLinksAsOnWebButNeverInsideThem() {
        val bold = ChatText.spans("**hi @bob see https://x.com/a_b_c**")
        assertEquals("hi @bob see https://x.com/a_b_c", bold.joinToString("") { it.text })
        assertTrue(bold.all { it.bold })
        assertEquals("https://x.com/a_b_c", bold.last().url)
        // a trailing marker that closes nothing is the URL's (web keeps `a_` here: the `_b_` before it is already closed)
        assertEquals("https://x.com/a_", ChatText.spans("a _b_ c https://x.com/a_").single { it.url != null }.url)
        assertTrue(ChatText.spans("a _b_ c https://x.com/a_").first { it.text == "b" }.italic)
        // `_` right after a mention is inside a word, as on web (`@bob_x_` stays plain)
        assertTrue(ChatText.spans("hi @bob_x_").none { it.italic }, "${ChatText.spans("hi @bob_x_")}")
        assertEquals("hi @bob_x_", ChatText.spans("hi @bob_x_").joinToString("") { it.text })
        // only the part of a trailing run that closes something leaves the link
        assertEquals("https://x.com/a_", ChatText.spans("**see https://x.com/a_**").single { it.url != null }.url)
        // a link closed by markers that opened before it ends where web ends it; one without an opener keeps them
        assertEquals("https://x.com/a_b", ChatText.spans("_https://x.com/a_b_").single().url)
        assertTrue(ChatText.spans("_https://x.com/a_b_").single().italic)
        assertEquals("https://x.com", ChatText.spans("~~https://x.com~~ gone").first().url)
        assertEquals("https://x.com/a_b_", ChatText.spans("see https://x.com/a_b_").last().url)
        // markers inside a url never pair with markers outside it
        val url = ChatText.spans("*look* https://x.com/*a*_b_ and _this_")
        assertEquals("https://x.com/*a*_b_", url.single { it.url != null }.url)
        assertTrue(url.single { it.url != null }.let { !it.italic && !it.bold })
        assertTrue(url.first { it.text == "this" }.italic)
        // a code span shows a link or mention inside it as typed, not as a link
        val code = ChatText.spans("`curl https://x.com/a and @bob`")
        assertEquals(listOf(ChatSpan("curl https://x.com/a and @bob", code = true)), code)
        // the moderation help keeps its placeholder, escapes drop their backslash, snake_case stays
        assertEquals("!ban <user> [30d]", ChatText.spans("!ban <user> [30d]").joinToString("") { it.text })
        assertEquals("*not*", ChatText.spans("\\*not\\*").single().text)
        assertEquals(listOf(ChatSpan("my_var_name")), ChatText.spans("my_var_name"))
        // a placeholder character the sender typed is not taken for a link
        assertEquals("a \uFFFD b", ChatText.spans("a \uFFFC b https://x.com").first().text.take(5))
    }

    @Test
    fun spansBoldMentionsLinksAndMarkdownButNeverInsideLinks() {
        val spans = ChatText.spans("hey @rainkiss this is _urgent_ see https://x.com/a_b_c")
        assertEquals("hey @rainkiss this is urgent see https://x.com/a_b_c", spans.joinToString("") { it.text })
        assertTrue(spans.first { it.text == "@rainkiss" }.bold)
        assertTrue(spans.first { it.text == "urgent" }.italic)
        assertEquals("https://x.com/a_b_c", spans.last().url)
        // an Ecency profile link shows as @name and opens the profile
        val profile = ChatText.spans(ChatText.content("hi @alice").text)
        assertEquals("hi @alice", profile.joinToString("") { it.text })
        assertEquals("https://ecency.com/@alice", profile.last().url)
        // a hive signing link is a link with its padding
        val hive = ChatText.spans("open hive://sign/op/abc.. now")
        assertEquals("hive://sign/op/abc..", hive.first { it.url != null }.url)
        // a mention right at the start, or after a leading space
        assertTrue(ChatText.spans(" @bob hi").first { it.text == "@bob" }.bold)
        assertTrue(ChatText.spans("@bob hi").first { it.text == "@bob" }.bold)
        assertTrue(ChatText.spans("mail me@bob.com").none { it.bold })
    }

    @Test
    fun mentionsAreFoundAndInsertedAsRnDoes() {
        assertEquals(6 to "al", ChatText.mentionQuery("hello @al"))
        assertEquals(0 to "", ChatText.mentionQuery("@"))
        assertNull(ChatText.mentionQuery("mail@al"))
        assertNull(ChatText.mentionQuery("hello @al "))
        assertEquals("hello @alice ", ChatText.insertMention("hello @al", 6, "al", "alice"))
        assertEquals("@alice x", ChatText.insertMention("@al x", 0, "al", "alice"))
        val users = listOf(ChatUser("1", username = "bob"), ChatUser("2", username = "alice"), ChatUser("3", username = "albert"), ChatUser("4"))
        assertEquals(listOf("albert", "alice"), ChatText.suggestions(users, "al").map { ChatText.mentionName(it) })
        assertEquals(3, ChatText.suggestions(users, "").size)
        assertTrue(ChatText.suggestions(users, null).isEmpty())
        assertEquals(8, ChatText.suggestions((1..20).map { ChatUser("$it", username = "user$it") }, "user").size)
    }

    @Test
    fun typingAndJoinTextsAreRns() {
        assertNull(ChatText.typing(emptyList()))
        assertEquals("a is typing...", ChatText.typing(listOf("a")))
        assertEquals("a and b are typing...", ChatText.typing(listOf("a", "b")))
        assertEquals("a, b, and c are typing...", ChatText.typing(listOf("a", "b", "c")))
        assertEquals("a, b, and 3 others are typing...", ChatText.typing(listOf("a", "b", "c", "d", "e")))
        val now = 1_791_288_000_000L
        assertEquals("joined 2 hours ago", ChatText.joinedSuffix(now - 2 * 3_600_000, now))
        assertEquals("joined", ChatText.joinedSuffix(0, now))
        val post = ChatPost("p", type = "system_join_channel", addedUserId = "u1", createAt = now - 60_000)
        assertEquals("@carol joined a minute ago", ChatText.body(post, mapOf("u1" to ChatUser("u1", username = "carol")), now))
        assertEquals("x".repeat(100) + "...", ChatText.quote("x".repeat(101)))
    }
