class ChatFormatTest {
    private val g = Json.parseToJsonElement(ChatGoldens.JSON).jsonObject

    @Test
    fun thousandsOfInlineMatchesSideBySideDoNotGrowTheStack() {
        // "*a* " x 4000 is 16 KB, Mattermost's post limit; 16000 matches to leave no doubt
        for (n in listOf(4_000, 16_000)) {
            val text = "*a* ".repeat(n)
            val inline = ChatInlineMarkdown.parse(text)
            assertEquals(n, inline.count { it.italic && it.text == "a" })
            assertEquals(text.replace("*", ""), inline.joinToString("") { it.text })
        }
        // a message the screen reads marks in: up to MAX_MARKDOWN characters
        val spans = ChatText.spans("*a* ".repeat(ChatText.MAX_MARKDOWN / 4))
        assertEquals(ChatText.MAX_MARKDOWN / 4, spans.count { it.italic && it.text == "a" })
        val mixed = "**b** ~~s~~ `c` _i_ ".repeat(400)
        val m = ChatText.spans(mixed)
        assertEquals(400, m.count { it.code && it.text == "c" })
        assertEquals(400, m.count { it.strike && it.text == "s" })
    }

    @Test
    fun aMessageLongerThanTheMarkdownCapShowsItsMarksAsTypedButKeepsItsLinks() {
        val long = "**bold** https://x.com/a_ " + "x".repeat(ChatText.MAX_MARKDOWN)
        val spans = ChatText.spans(long)
        assertTrue(spans.none { it.bold || it.italic || it.code || it.strike })
        assertTrue(spans.first().text.startsWith("**bold**"))
        assertEquals("https://x.com/a_", spans.single { it.url != null }.url)
    }

    @Test
    fun nestingReadsAndDelimiterSoupStaysBounded() {
        val x = ChatInlineMarkdown.parse("**~~_x_~~**").single()
        assertEquals("x", x.text)
        assertTrue(x.strike && x.bold && x.italic)
        // remarkable's nesting limit (20 levels) leaves the rest as text instead of recursing further
        val soup = "*_".repeat(500) + "x" + "_*".repeat(500)
        assertTrue(ChatInlineMarkdown.parse(soup).joinToString("") { it.text }.contains("x"))
    }

    private fun list(key: String) = g[key]!!.jsonArray.map { it.jsonObject }
    private fun JsonObject.s(key: String) = this[key]?.jsonPrimitive?.contentOrNull
    private fun JsonElement.strings() = jsonArray.map { it.jsonPrimitive.content }

    @Test
    fun unreadBadgeMatchesRn() {
        for (case in list("unread")) {
            val channel = ChatChannel.parse(JsonObject(case["channel"]!!.jsonObject + ("id" to JsonPrimitive("c"))))!!
