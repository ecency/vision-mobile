    }

    @Test
    fun banNoticeMatchesRn() {
        val now = 1_791_288_000_000L
        for (case in list("ban")) {
            val delta = case["delta"]!!.jsonPrimitive.long
            val reason = case.s("reason")
            val info = ChatBan.info((now + delta).toDouble(), reason, now)
            // deliberate difference: native's plural message says "1 hour" where RN's says "1 hours"
            val expected = case.s("notice")?.replace("in about 1 hours.", "in about 1 hour.")
            assertEquals(expected, info?.let { ChatBan.notice(it, now) }, "ban +$delta $reason")
        }
        for (case in list("banInfo")) {
            val input = case["input"]!!
            val body = buildJsonObject {
                put("prop", ChatApiException.BAN_PROP)
                put("bannedUntil", input)
                case.s("reason")?.let { put("reason", it) }
            }
            val e = ChatApiException.of(403, body.toString())
            assertTrue(e.isBan)
            val out = case["out"]
            val info = ChatBan.info(e.bannedUntil, e.reason, now)
            if (out == null || out is JsonNull) assertNull(info, "ban info of $input") else assertEquals(out.jsonObject["bannedUntil"]!!.jsonPrimitive.long, info?.bannedUntil, "ban info of $input")
        }
    }

