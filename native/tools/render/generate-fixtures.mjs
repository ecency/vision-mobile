  video_embeds: 'https://www.youtube.com/watch?v=dQw4w9WgXcQ\n\nhttps://3speak.tv/watch?v=someuser/abcdefgh\n\nhttps://vimeo.com/123456789',
  social_embeds: 'https://twitter.com/hiveblocks/status/1234567890123456789\n\nhttps://www.instagram.com/p/ABCdef123/',
