// Expected post-renderer output, produced by @ecency/render-helper itself. The Kotlin renderer is a
// port, and these fixtures are its golden oracle. JS never runs in the app.
//
//   cd native/tools/render && npm ci
//   node generate-fixtures.mjs ../../shared/src/commonTest/kotlin/com/ecency/core/render/RenderFixtures.kt
import { writeFileSync } from 'node:fs'

// The RN app runs the browser build, where `window` exists and code blocks get no lolight
// highlighting. Defining it here gives the node build the same behaviour.
globalThis.window = globalThis
const rh = await import('@ecency/render-helper')
const out = process.argv[2]
if (!out) throw new Error('usage: generate-fixtures.mjs <output.kt>')

const IMAGE_PROXY = 'https://images.ecency.com'
rh.setProxyBase(IMAGE_PROXY)

