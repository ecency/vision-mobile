// Entity tables used by the native DOM/sanitizer port, extracted from the exact packages
// @ecency/render-helper runs with. Pure data: the decoders themselves are ported by hand.
//
//   cd native/tools/render && npm ci
//   node generate-entity-tables.mjs ../../shared/src/commonMain/kotlin/com/ecency/core/render/dom/EntityTables.kt
import { writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'

const require = createRequire(import.meta.url)
const out = process.argv[2]
if (!out) throw new Error('usage: generate-entity-tables.mjs <output.kt>')

// @xmldom/xmldom 0.9.12: name -> value map used for `&name;` / `&name` in text/html parsing.
const { HTML_ENTITIES } = require('@xmldom/xmldom/lib/entities.js')
// entities 6.0.1 (render-helper's own decodeHTML) and 7.0.1 (htmlparser2's tokenizer) tries.
const v6 = await import('entities/decode')
const v7 = await import('./node_modules/htmlparser2/node_modules/entities/dist/esm/decode.js')

const esc = (s) => [...s].map((ch) => {
  const out = []
  for (let i = 0; i < ch.length; i++) {
    const c = ch.charCodeAt(i)
    if (c >= 0x20 && c < 0x7f && ch[i] !== '"' && ch[i] !== '\\' && ch[i] !== '$') out.push(ch[i])
    else out.push('\\u' + c.toString(16).padStart(4, '0'))
  }
  return out.join('')
}).join('')

function chunks(str, size = 1500) {
  const parts = []
  for (let i = 0; i < str.length; i += size) parts.push(str.slice(i, i + size))
  return parts.map((p) => `        "${esc(p)}",`).join('\n')
}

const u16 = (arr) => String.fromCharCode(...arr)
const htmlEntities = Object.entries(HTML_ENTITIES).map(([k, v]) => `${k}\u0000${v}\u0000`).join('')

writeFileSync(out, `// GENERATED by native/tools/render/generate-entity-tables.mjs. Do not edit by hand.
package com.ecency.core.render.dom

internal object EntityTables {
    /** @xmldom/xmldom HTML_ENTITIES as name NUL value NUL pairs (${Object.keys(HTML_ENTITIES).length} entries). */
    val XMLDOM_HTML: Map<String, String> by lazy {
        val s = listOf(
${chunks(htmlEntities)}
        ).joinToString("")
        val map = HashMap<String, String>(4096)
        var i = 0
        while (i < s.length) {
            val a = s.indexOf('\\u0000', i)
            val b = s.indexOf('\\u0000', a + 1)
            map[s.substring(i, a)] = s.substring(a + 1, b)
            i = b + 1
        }
        map
    }

    /** entities 6.0.1 htmlDecodeTree (${v6.htmlDecodeTree.length} uint16). */
    val TREE_V6: String by lazy {
        listOf(
${chunks(u16(v6.htmlDecodeTree))}
        ).joinToString("")
    }

    /** entities 7.0.1 htmlDecodeTree (${v7.htmlDecodeTree.length} uint16). */
    val TREE_V7: String by lazy {
        listOf(
${chunks(u16(v7.htmlDecodeTree))}
        ).joinToString("")
    }
}
`)
console.log('wrote', out)
