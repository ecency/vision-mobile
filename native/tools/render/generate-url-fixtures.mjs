//   node generate-url-fixtures.mjs ../../shared/src/commonTest/kotlin/com/ecency/core/render/url/UrlFixtures.kt
import { writeFileSync } from 'node:fs'
import { kt } from './kotlin-literal.mjs'

const out = process.argv[2]
if (!out) throw new Error('usage: generate-url-fixtures.mjs <output.kt>')

const WPT = 'https://raw.githubusercontent.com/web-platform-tests/wpt/master/url/resources/urltestdata.json'
