// 2. Autolinker

const regexLib = require('autolinker/dist/commonjs/regex-lib.js')
const { tldRegex } = require('autolinker/dist/commonjs/matcher/tld-regex.js')
const { UrlMatcher } = require('autolinker/dist/commonjs/matcher/url-matcher.js')
const { UrlMatchValidator } = require('autolinker/dist/commonjs/matcher/url-match-validator.js')

const N = 0x10000
const LINE_TERMINATORS = [0x0a, 0x0d, 0x2028, 0x2029]
const isJsSpace = (c) => /\s/.test(String.fromCharCode(c))

// ES2015+ Canonicalize(ch) for non-unicode ignoreCase regexes.
const canon = new Uint16Array(N)
for (let c = 0; c < N; c++) {
  const u = String.fromCharCode(c).toUpperCase()
  if (u.length !== 1) { canon[c] = c; continue }
  const cu = u.charCodeAt(0)
  canon[c] = c >= 128 && cu < 128 ? c : cu
}

// Membership of a single code unit in a JS regex fragment, evaluated by V8 itself.
const setOf = (classSource) => {
  const re = new RegExp(`^${classSource}$`)
  const s = new Uint8Array(N)
  for (let c = 0; c < N; c++) s[c] = re.test(String.fromCharCode(c)) ? 1 : 0
  return s
}

// --- tiny parser for the subset of JS regex syntax Autolinker uses ---------------------------
function parseRegex(src) {
  let i = 0
  const peek = () => src[i]
  const hex = (n) => { const h = src.slice(i, i + n); i += n; return parseInt(h, 16) }

  function parseAlt() {
    const alts = [parseSeq()]
    while (peek() === '|') { i++; alts.push(parseSeq()) }
    return { t: 'alt', alts }
  }
  function parseSeq() {
    const items = []
    while (i < src.length && peek() !== '|' && peek() !== ')') {
      const atom = parseAtom()
      parseQuant(atom)
      items.push(atom)
    }
    return items
  }
  function parseQuant(atom) {
    const c = peek()
    if (c === '*' || c === '+' || c === '?') { atom.q = c; i++ }
    else if (c === '{' && /^\{\d+(,\d*)?\}/.test(src.slice(i))) {
      const m = src.slice(i).match(/^\{\d+(,\d*)?\}/)
      atom.q = m[0]; i += m[0].length
    } else return
    if (peek() === '?') { atom.lazy = true; i++ }
  }
  function escapeCode() {
    // after a backslash, returns a code unit, or a {set} for class escapes
    const c = src[i++]
    if (c === 'u') return hex(4)
    if (c === 'x') return hex(2)
    if (c === 'd') return { set: setOf('\\d') }
    if (c === 'D') return { set: setOf('\\D') }
    if (c === 's') return { set: setOf('\\s') }
    if (c === 'S') return { set: setOf('\\S') }
    if (c === 'w') return { set: setOf('\\w') }
    if (c === 'W') return { set: setOf('\\W') }
    if (c === 'n') return 0x0a
    if (c === 't') return 0x09
    if (c === 'r') return 0x0d
    if (/[0-9]/.test(c)) throw new Error('unexpected digit escape at ' + i)
    return c.charCodeAt(0) // identity escape
  }
  function parseClass() {
    i++ // [
    let neg = false
    if (peek() === '^') { neg = true; i++ }
    const s = new Uint8Array(N)
    let first = true
    while (first || peek() !== ']') {
      first = false
      let lo
      if (peek() === '\\') { i++; lo = escapeCode() } else lo = src.charCodeAt(i++)
      if (typeof lo === 'object') { for (let c = 0; c < N; c++) if (lo.set[c]) s[c] = 1; continue }
      if (peek() === '-' && src[i + 1] !== ']') {
        i++
        let hi
        if (peek() === '\\') { i++; hi = escapeCode() } else hi = src.charCodeAt(i++)
        if (typeof hi === 'object') throw new Error('class escape as range end')
        for (let c = lo; c <= hi; c++) s[c] = 1
      } else s[lo] = 1
    }
    i++ // ]
    return { t: 'class', members: s, neg }
  }
  function parseAtom() {
    const c = peek()
    if (c === '(') {
      i++
      let kind = 'cap'
      if (src.startsWith('?:', i)) { kind = 'nc'; i += 2 }
      else if (src.startsWith('?=', i)) { kind = 'la'; i += 2 }
      else if (src.startsWith('?!', i)) { kind = 'nla'; i += 2 }
      const body = parseAlt()
      if (src[i++] !== ')') throw new Error('unbalanced group')
      return { t: 'group', kind, body }
    }
    if (c === '[') return parseClass()
    if (c === '^' || c === '$') { i++; return { t: 'anchor', a: c } }
    if (c === '.') {
      i++
      const s = new Uint8Array(N).fill(1)
      for (const lt of LINE_TERMINATORS) s[lt] = 0
      return { t: 'class', members: s, neg: false }
    }
    if (c === '\\') {
      i++
      if (/[1-9]/.test(peek())) {
        const m = src.slice(i).match(/^[0-9]+/)
        i += m[0].length
        return { t: 'backref', n: Number(m[0]) }
      }
      const e = escapeCode()
      if (typeof e === 'object') return { t: 'class', members: e.set, neg: false }
      return { t: 'char', c: e }
    }
    i++
    return { t: 'char', c: src.charCodeAt(i - 1) }
  }
  const ast = parseAlt()
  if (i !== src.length) throw new Error('regex not fully parsed at ' + i)
  return ast
}

function walk(node, fn) {
  fn(node)
  if (node.t === 'alt') node.alts.forEach((seq) => seq.forEach((n) => walk(n, fn)))
  if (node.t === 'group') walk(node.body, fn)
}

// Builds the alphabet reduction for a set of regexes that share one input mapping.
function reduce(regexes, ignoreCase) {
  const fold = (c) => (ignoreCase ? canon[c] : c)
  const asts = regexes.map(parseRegex)
  const classes = []
  const distinguished = new Set()
  for (const ast of asts) {
    walk(ast, (n) => {
      if (n.t === 'char') distinguished.add(fold(n.c))
      if (n.t === 'class') {
        // membership of a folded code unit s
        const pos = new Uint8Array(N)
        for (let c = 0; c < N; c++) if (n.members[c]) pos[fold(c)] = 1
        const m = new Uint8Array(N)
        for (let s = 0; s < N; s++) m[s] = pos[s] ^ (n.neg ? 1 : 0)
        n.m = m
        classes.push(n)
      }
    })
  }
  for (const d of distinguished) if (d >= 0xd800 && d <= 0xdfff) throw new Error('surrogate literal')
  const sig = (s) => classes.map((k) => k.m[s]).join('')
  // signature groups of folded, non-distinguished units
  const groupRep = new Map()
  const groupSig = new Map()
  let nextPua = 0xe000
  const used = new Set(distinguished)
  const sigs = new Array(N)
  for (let s = 0; s < N; s++) {
    if (distinguished.has(s)) continue
    const g = sig(s)
    sigs[s] = g
    if (!groupRep.has(g) && !(s >= 0xd800 && s <= 0xdfff)) { groupRep.set(g, s); used.add(s) }
  }
  for (let s = 0; s < N; s++) {
    if (distinguished.has(s)) continue
    const g = sigs[s]
    if (!groupRep.has(g)) {
      while (used.has(nextPua)) nextPua++
      groupRep.set(g, nextPua); used.add(nextPua)
    }
  }
  for (const [g, rep] of groupRep) groupSig.set(rep, g)
  const R = (s) => (distinguished.has(s) ? s : groupRep.get(sigs[s]))
  const table = new Uint16Array(N)
  for (let c = 0; c < N; c++) table[c] = R(fold(c))
  // the reduced alphabet: everything the table can produce
  const alphabet = [...new Set(table)].sort((a, b) => a - b)
  const memberOf = (k, a) => (distinguished.has(a) ? k.m[a] : Number(groupSig.get(a)[classes.indexOf(k)]))

  const esc = (c) => (/[A-Za-z0-9]/.test(String.fromCharCode(c)) ? String.fromCharCode(c) : '\\u' + c.toString(16).padStart(4, '0'))
  const emitClass = (k) => {
    const members = alphabet.filter((a) => memberOf(k, a) === 1)
    if (members.length === 0) return '(?!)'
    let out = '['
    for (let j = 0; j < members.length; j++) {
      let e = j
      while (e + 1 < members.length && members[e + 1] === members[e] + 1) e++
      out += esc(members[j]) + (e > j ? (e > j + 1 ? '-' : '') + esc(members[e]) : '')
      j = e
    }
    return out + ']'
  }
  const emit = (n) => {
    let out
    switch (n.t) {
      case 'alt': return n.alts.map((seq) => seq.map(emit).join('')).join('|')
      case 'char': out = esc(fold(n.c)); break
      case 'class': out = emitClass(n); break
      case 'backref': out = '\\' + n.n; break
      case 'anchor': out = n.a === '^' ? '^' : '(?![\\s\\S])'; break
      case 'group': out = { cap: '(', nc: '(?:', la: '(?=', nla: '(?!' }[n.kind] + emit(n.body) + ')'; break
    }
    if (n.q) out += n.q + (n.lazy ? '?' : '')
    return out
  }
  // Self check: the rewritten regex must agree with the original on every code unit for every class.
  for (const k of classes) {
    for (let c = 0; c < N; c++) {
      if (memberOf(k, table[c]) !== k.m[fold(c)]) throw new Error('reduction broke a class at ' + c)
    }
  }
  return { table, patterns: asts.map(emit) }
}

// run-length encoding of a 64K table: "start-end:value" in hex, value "i" means identity
function rle(table) {
  const runs = []
  let c = 0
  while (c < N) {
    const ident = table[c] === c
    let e = c
    if (ident) while (e + 1 < N && table[e + 1] === e + 1) e++
    else while (e + 1 < N && table[e + 1] === table[c]) e++
    runs.push(`${c.toString(16)}-${e.toString(16)}:${ident ? 'i' : table[c].toString(16)}`)
    c = e + 1
  }
  return runs.join(',')
}
function ranges(set) {
  const out = []
  for (let c = 0; c < N; c++) {
    if (!set[c]) continue
    let e = c
    while (e + 1 < N && set[e + 1]) e++
    out.push(`${c.toString(16)}-${e.toString(16)}`)
    c = e
  }
  return out.join(',')
}

const urlMatcherRegex = new UrlMatcher({ tagBuilder: null, stripPrefix: {}, stripTrailingSlash: true, decodePercentEncoding: true }).matcherRegex
if (urlMatcherRegex.flags !== 'gi') throw new Error('unexpected url regex flags ' + urlMatcherRegex.flags)
const alnum = regexLib.alphaNumericAndMarksCharsStr
const decimal = regexLib.decimalNumbersStr

// UrlMatcher.matcherRegex is matched by a hand-written scanner in Autolinker.kt (Kotlin/Native's regex
// engine is far too slow on it and mishandles its lookahead idiom). The scanner hard-codes this
// structure, so rebuild the regex from these parts and insist it is exactly Autolinker's.
const suffixChars = alnum + '\\-+&@#/%=~_()|\'$*\\[\\]{}?!:,.;^\u2713'
const suffixEndChars = alnum + '\\-+&@#/%=~_()|\'$*\\[\\]{}\u2713'
const schemeSrc = '(?:[A-Za-z][-.+A-Za-z0-9]{0,63}:(?![A-Za-z][-.+A-Za-z0-9]{0,63}:\\/\\/)(?!\\d+\\/?)(?:\\/\\/)?)'
const rebuilt = [
  '(?:', '(', schemeSrc, regexLib.getDomainNameStr(2), ')', '|',
  '(', '(\\/\\/)?', '(?:www\\.)', regexLib.getDomainNameStr(6), ')', '|',
  '(', '(\\/\\/)?', regexLib.getDomainNameStr(10) + '\\.', tldRegex.source, '(?![-' + regexLib.alphaNumericCharsStr + '])', ')',
  ')', '(?::[0-9]+)?', '(?:' + '[/?#](?:[' + suffixChars + ']*[' + suffixEndChars + '])?' + ')?',
].join('')
if (rebuilt !== urlMatcherRegex.source) throw new Error('UrlMatcher regex changed; update Autolinker.kt and this generator')
if (regexLib.alphaNumericCharsStr !== alnum) throw new Error('alphaNumericCharsStr differs from alphaNumericAndMarksCharsStr')
const domainLabel = '[' + alnum + '](?:[' + alnum + '\\-_]{0,61}[' + alnum + '])?'
if (!regexLib.getDomainNameStr(2).includes(domainLabel)) throw new Error('domain label regex changed')

// Character classes as the /i regex sees them: code unit c is in class K iff canon(c) is the
// canonical form of some member of K.
const foldedSet = (classSource) => {
  const members = setOf(classSource)
  const canonMembers = new Uint8Array(N)
  for (let c = 0; c < N; c++) if (members[c]) canonMembers[canon[c]] = 1
  const s = new Uint8Array(N)
  for (let c = 0; c < N; c++) s[c] = canonMembers[canon[c]]
  return s
}
const canonTable = new Uint16Array(N)
for (let c = 0; c < N; c++) canonTable[c] = canon[c]

// Case-sensitive regexes still used per match: rewrite them over a reduced alphabet.
// Same source as UrlMatcher.matchHasInvalidCharAfterTld builds at call time.
const invalidAfterTldSource = '^((.?\/\/)?[-.' + alnum + ']*[-' + alnum + ']\\.[-' + alnum + ']+)'
const plainReduced = reduce([UrlMatchValidator.hasWordCharAfterProtocolRegex.source, invalidAfterTldSource], false)

const tlds = tldRegex.source.replace(/^\(\?:/, '').replace(/\)$/, '').split('|')
for (const t of tlds) if (!/^[^()|?*+\\[\]{}.^$]+$/.test(t)) throw new Error('unexpected tld ' + t)

writeFileSync(join(outDir, 'AutolinkerData.kt'), `${HEADER('autolinker 3.16.2 (regex-lib, tld-regex, url-matcher, url-match-validator)')}package com.ecency.core.render.markdown

/** Autolinker's character classes, TLD list and two small regexes (see generate-markdown-data.mjs). */
internal object AutolinkerData {
    /** UrlMatchValidator.hasWordCharAfterProtocolRegex, over [PLAIN_TABLE]-mapped input. */
${chunked('WORD_CHAR_AFTER_PROTOCOL_PATTERN', plainReduced.patterns[0])}
    /** The regex built in UrlMatcher.matchHasInvalidCharAfterTld, over [PLAIN_TABLE]-mapped input. */
${chunked('INVALID_CHAR_AFTER_TLD_PATTERN', plainReduced.patterns[1])}
    /** Input mapping (alphabet reduction) for the two patterns above; indices are unchanged. */
${chunked('PLAIN_TABLE', rle(plainReduced.table))}
    /** JS Canonicalize() for case-insensitive (non-unicode) regexes, per code unit. */
${chunked('CANON_TABLE', rle(canonTable))}
    /** regex-lib alphaNumericAndMarksCharsStr, as UTF-16 code unit ranges. */
${chunked('ALPHA_NUMERIC_AND_MARKS', ranges(setOf('[' + alnum + ']')))}
    /** The same class as the case-insensitive URL regex matches it. */
${chunked('URL_ALNUM', ranges(foldedSet('[' + alnum + ']')))}
    /** decimalNumbersStr as the case-insensitive URL regex matches it (IP addresses). */
${chunked('URL_DECIMAL', ranges(foldedSet('[' + decimal + ']')))}
    /** The URL suffix body class, case-insensitive. */
${chunked('URL_SUFFIX', ranges(foldedSet('[' + suffixChars + ']')))}
    /** The URL suffix last-character class, case-insensitive. */
${chunked('URL_SUFFIX_END', ranges(foldedSet('[' + suffixEndChars + ']')))}
    /** The TLDs of tld-regex in regex order, lower case, "|" separated. */
${chunked('TLDS', tlds.join('|'))}}
`)

