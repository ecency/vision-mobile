// Generates the data tables of the Kotlin markdown port (com.ecency.core.render.markdown) from the
// installed oracle packages: remarkable's HTML5 entity table and the Autolinker character classes,
// TLD list and URL regexes. JS never runs in the app; this only runs offline.
//
//   cd native/tools/render && npm ci
//   node generate-markdown-data.mjs
//
// Autolinker's regexes are JavaScript regexes over UTF-16 code units with JS case folding. Kotlin
// regexes (JVM and Kotlin/Native) work on code points and fold case differently. The big URL regex
// is matched by a hand-written scanner (UrlScanner.kt) fed with the character classes emitted here,
// computed as the /i regex sees them. The two small per-match regexes are rewritten into an
// equivalent form over a reduced alphabet: every input code unit is first mapped through a table
// that collapses characters no part of the regex can tell apart into one representative, so the
// rewritten classes are tiny and contain no surrogates.
import { readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const require = createRequire(import.meta.url)
const outDir = join(here, '../../shared/src/commonMain/kotlin/com/ecency/core/render/markdown')

const HEADER = (what) =>
  `// GENERATED by native/tools/render/generate-markdown-data.mjs from ${what}. Do not edit by hand.\n`

// ---------------------------------------------------------------------------------------------
// Kotlin string literal helpers

const kstr = (s) => {
  let out = '"'
  for (let i = 0; i < s.length; i++) {
    const c = s.charCodeAt(i)
    if (c === 0x22) out += '\\"'
    else if (c === 0x5c) out += '\\\\'
    else if (c === 0x24) out += '\\$'
    else if (c >= 0x20 && c < 0x7f) out += s[i]
    else out += '\\u' + c.toString(16).padStart(4, '0')
  }
  return out + '"'
}

// Long data goes in as several constants so no single JVM string constant gets near 64 KB.
const chunked = (name, s, size = 12000) => {
  const parts = []
  for (let i = 0; i < s.length; i += size) parts.push(s.slice(i, i + size))
  return `    val ${name}: String = listOf(\n${parts.map((p) => '        ' + kstr(p) + ',').join('\n')}\n    ).joinToString("")\n`
}

