// Golden vectors for the post menu operations and the vote value estimate, from the @ecency/sdk the RN app
// ships. Run from the RN app root (it has node_modules):
//   node native/tools/golden/generate-feedx.mjs native/shared/src/commonTest/kotlin/com/ecency/core/app/FeedxGoldens.kt
//
// Synthetic accounts and values only.
import { createRequire } from 'node:module'
import { writeFileSync } from 'node:fs'
import { join } from 'node:path'

const require = createRequire(join(process.cwd(), 'package.json'))
const sdk = await import(require.resolve('@ecency/sdk'))

const out = process.argv[2]
if (!out) throw new Error('usage: generate-feedx.mjs <output.kt>')
const k = (s) => JSON.stringify(s).replace(/\$/g, '\\$')
const d = (x) => (Number.isInteger(x) ? x.toFixed(1) : String(x))

const ops = [
  ['reblog', sdk.buildReblogOp('spike-alice', 'spike-bob', 'hello-world', false)],
  ['reblog_undo', sdk.buildReblogOp('spike-alice', 'spike-bob', 'hello-world', true)],
  ['ignore', sdk.buildIgnoreOp('spike-alice', 'spike-bob')],
  ['pin_community', sdk.buildPinPostOp('spike-mod', 'hive-100001', 'spike-bob', 'hello-world', true)],
  ['unpin_community', sdk.buildPinPostOp('spike-mod', 'hive-100001', 'spike-bob', 'hello-world', false)],
  ['mute_post', sdk.buildMutePostOp('spike-mod', 'hive-100001', 'spike-bob', 'hello-world', 'off topic', true)],
  ['unmute_post', sdk.buildMutePostOp('spike-mod', 'hive-100001', 'spike-bob', 'hello-world', 'restored 🐝', false)],
  ['delete', sdk.buildDeleteCommentOp('spike-alice', 're-hello')],
]

// pin to blog: account_update2 over an existing posting_json_metadata
// (an empty base is the wipe case a stripped node read would produce; ProfileMetadataGuard decides when an
// empty base is allowed, so it is tested there and not enshrined here)
const existing = [
  '{"profile":{"name":"Spike","about":"x","pinned":"old-post","version":2},"other":1}',
  '{"profile":{"name":"Spike","cover_image":"https://example.com/c.png"}}',
  '{"profile":{"name":"Spike","tokens":[{"symbol":"LEO","type":"ENGINE"}],"custom_key":{"a":1}},"apps":["x"]}',
]
const pins = []
for (const [i, meta] of existing.entries()) {
  for (const pinned of ['new-post', null]) {
    const json = sdk.buildPostingJsonMetadata({ existingPostingJsonMetadata: meta, profile: { pinned } })
    pins.push(`        PinCase(${k(meta)}, ${pinned === null ? 'null' : k(pinned)}, ${k(JSON.stringify(sdk.buildAccountUpdate2Op('spike-alice', '', json, [])))}),`)
  }
}

// pin reply: the parent re-posted with pinned_reply (RN useUpdateReply over buildCommentOp)
const parentMeta = { tags: ['ecency', 'test'], app: 'ecency/3.5.0-mobile', image: ['https://example.com/a.png'] }
const pinReply = sdk.buildCommentOp('spike-alice', 'hello-world', '', 'ecency', 'Hello', 'Body text', { ...parentMeta, pinned_reply: 'spike-bob/re-hello' })
const unpinReply = sdk.buildCommentOp('spike-alice', 'hello-world', '', 'ecency', 'Hello', 'Body text', { ...parentMeta, pinned_reply: undefined })

// vote value: synthetic account with a full manabar (last update long ago, so no clock dependence)
const props = {
  fundRecentClaims: 6.2e17, fundRewardBalance: 850000.123, base: 0.235, quote: 1.0,
  votePowerReserveRate: 10, lastHardfork: 28, currentHardforkVersion: '1.28.0',
}
const legacyProps = { ...props, lastHardfork: 27, currentHardforkVersion: '1.27.0' }
const accounts = [
  ['whale', '5000000000.000000 VESTS', '0.000000 VESTS', '0.000000 VESTS'],
  ['dolphin', '20000000.000000 VESTS', '1000000.000000 VESTS', '500000.000000 VESTS'],
  ['minnow', '15000.123456 VESTS', '0.000000 VESTS', '0.000000 VESTS'],
]
const votes = []
for (const [name, vesting, delegated, received] of accounts) {
  const account = {
    name, vesting_shares: vesting, delegated_vesting_shares: delegated, received_vesting_shares: received,
    vesting_withdraw_rate: '0.000000 VESTS', to_withdraw: 0, withdrawn: 0,
    voting_manabar: { current_mana: '0', last_update_time: 1000 },
  }
  for (const [label, p] of [['hf28', props], ['legacy', legacyProps]]) {
    for (const weight of [10000, 5000, 100, 1]) {
      const vPower = sdk.votingPower(account) * 100
      const value = sdk.votingValue(account, p, vPower, weight)
      votes.push(`        VoteValueCase(${k(name)}, ${k(vesting)}, ${k(delegated)}, ${k(received)}, ${label === 'hf28' ? 28 : 27}, ${weight}, ${d(value)}),`)
    }
  }
}

writeFileSync(out, `// GENERATED by native/tools/golden/generate-feedx.mjs from @ecency/sdk. Do not edit by hand.
package com.ecency.core.app

object FeedxGoldens {
    /** SDK op builders as condenser JSON text. */
    val ops = mapOf(
${ops.map(([n, op]) => `        ${k(n)} to ${k(JSON.stringify(op))},`).join('\n')}
    )

    val pins = listOf(
${pins.join('\n')}
    )

    const val PIN_REPLY = ${k(JSON.stringify(pinReply))}
    const val UNPIN_REPLY = ${k(JSON.stringify(unpinReply))}
    const val PARENT_META = ${k(JSON.stringify(parentMeta))}

    /** Props used for every vote case (lastHardfork per case). */
    const val RECENT_CLAIMS = ${d(props.fundRecentClaims)}
    const val REWARD_BALANCE = ${d(props.fundRewardBalance)}
    const val BASE = ${d(props.base)}
    const val QUOTE = ${d(props.quote)}
    const val RESERVE_RATE = ${d(props.votePowerReserveRate)}

    val votes = listOf(
${votes.join('\n')}
    )
}

data class PinCase(val existing: String, val pinned: String?, val op: String)

data class VoteValueCase(
    val name: String,
    val vesting: String,
    val delegated: String,
    val received: String,
    val hardfork: Int,
    val weight: Int,
    val value: Double,
)
`)
console.log(`wrote ${ops.length} ops, ${pins.length} pin cases, ${votes.length} vote cases`)
