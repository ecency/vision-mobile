/** The text of `export const <name> = ...` through its closing top-level `};` (or `;` for a one-liner). */
const cut = (text, name) => {
  const start = text.indexOf(`export const ${name}`)
  if (start < 0) throw new Error(`no ${name}`)
  const firstLine = text.slice(start, text.indexOf('\n', start))
  if (firstLine.trimEnd().endsWith(';')) return firstLine + '\n'
  const end = text.indexOf('\n};\n', start)
  const oneExpr = text.indexOf(';\n\n', start)
  const stop = end < 0 ? oneExpr : oneExpr >= 0 && oneExpr < end && !text.slice(start, oneExpr).includes('{\n') ? oneExpr : end
  return text.slice(start, stop + 3) + '\n'
}

const emojiMap = JSON.parse(src('src/constants/emojiMap.json'))

// ---- the emoji map as Kotlin data ----
{
  const lines = Object.entries(emojiMap).map(([k, v]) => {
    if (k.includes('\t') || k.includes('\n') || v.includes('\t') || v.includes('\n')) throw new Error('separator in map')
    return `${k}\t${v}`
  })
  const chunks = []
  let cur = []
  let size = 0
  for (const l of lines) {
    if (size + l.length > 8000 && cur.length) {
      chunks.push(cur.join('\n'))
      cur = []
      size = 0
    }
    cur.push(l)
    size += l.length + 1
  }
  if (cur.length) chunks.push(cur.join('\n'))
  const kt = (s) => JSON.stringify(s).replace(/\$/g, '\\$')
  writeFileSync(outEmoji, `package com.ecency.core.app

// Generated by native/tools/golden/generate-chats.mjs from the RN app's src/constants/emojiMap.json; do not edit.
// One "name<TAB>emoji" line per entry, in the map's order.
internal object ChatEmojiData {
    val CHUNKS: List<String> = listOf(
${chunks.map((c) => `        ${kt(c)},`).join('\n')}
    )
}
`)
}

