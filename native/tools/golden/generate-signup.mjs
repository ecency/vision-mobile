// Golden vectors for the register screen: RN's own username rules (src/utils/usernameValidation.ts with
// src/constants/exchangeAccounts.ts), the email pattern of src/screens/register/registerScreen.tsx and
// src/utils/parseVersionNumber.ts, all run offline.
//
// Run from the RN app root:
//   node --no-warnings native/tools/golden/generate-signup.mjs native/shared/src/commonTest/kotlin/com/ecency/core/app/SignupGoldens.kt
//
// Synthetic names only.
import { register } from 'node:module'
import { readFileSync, writeFileSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const out = process.argv[2]
if (!out) throw new Error('usage: generate-signup.mjs <output.kt>')
register(pathToFileURL(join(dirname(fileURLToPath(import.meta.url)), 'rn-hooks.mjs')))
const rn = (p) => import(join(process.cwd(), 'src', p))
const { getUsernameError, hasRestrictedUsernamePrefix } = await rn('utils/usernameValidation.ts')
const { isExchangeLikeUsername, EXCHANGE_ACCOUNTS } = await rn('constants/exchangeAccounts.ts')
const parseVersionNumber = (await rn('utils/parseVersionNumber.ts')).default

// the email pattern is a literal inside the screen: read it from the source so the oracle is RN's own text
const screen = readFileSync(join(process.cwd(), 'src/screens/register/registerScreen.tsx'), 'utf8')
const m = screen.match(/const re =\s*\n?\s*(\/\^.*\$\/);/)
if (!m) throw new Error('email pattern not found in registerScreen.tsx')
const emailRe = eval(m[1])

const k = (s) => JSON.stringify(s).replace(/\$/g, '\\$')

const names = [
  '', 'a', 'ab', 'abc', 'abcd', 'a'.repeat(16), 'a'.repeat(17), 'good-name', 'good.name', 'goodname1', 'ab.cde', 'abc.de', 'abc.def',
  'abc..def', '.abc', 'abc.', '1abc', '-abc', 'abc-', 'ab--cd', 'abc_def', '_abc', 'abc.1de', 'abc.d-e', 'abc.de-', 'abc.d--e', 'ABC', 'Abc',
  'abc def', 'abc!', 'abcé', 'äbc', 'abc.def.ghi', 'a-b', 'a-b-c', 'abc-1', 'abc1-', 'a1b', 'a--', 'abc.-de', 'abc.d_e', 'x.y.z', 'abc.xy', 'spike-alice',
  'spike.alice', 'hive-125125', 'my.new-name1', 'ab1', 'a12', 'a1-', 'aaa.bbb.ccc.ddd', 'aaaa.bbbb.cccc.d',
  // exchange-like
  ...EXCHANGE_ACCOUNTS, 'huobipro', 'huobi.pro', 'coinex', 'gateio', 'mybittrex', 'bittrexx', 'bittrx', 'bitrex', 'upbitcoin', 'upbit', 'mxc', 'mxchive1',
  'blocktrade', 'blocktradess', 'block', 'change', 'changely', 'poloniex1', 'xpoloniex', 'poloni', 'deepcrypto', 'deepcrypto9', 'gopax', 'gopaxdeposit',
  'hitbtc', 'hitbtcx', 'onepage', 'onepagexx', 'probit', 'probithive2', 'bitget', 'bitgethiv', 'bdhive', 'bdhivesteem1', 'probit.hive', 'bit.trex',
  // restricted prefix
  'uid1', 'uid12345', 'uid', 'uidev', 'fluid1', 'u.i.d1', 'uid-1', 'uid.123', 'uidx1', 'uida', 'uid-abc', 'ui-d12', 'uid123456789012', 'u-id9aa',
]
const seen = new Set()
const usernameRows = names.filter((n) => !seen.has(n) && seen.add(n)).map((n) => {
  const e = getUsernameError(n)
  return `        Triple(${k(n)}, ${e ? k(e) : 'null'}, ${isExchangeLikeUsername(n)}),`
})
const prefixRows = ['uid1', 'UID1', 'u.i.d.1', 'uidev', 'fluid', 'uid', 'Uid-9', 'u_i_d_0x', 'xuid1', ' uid1', 'uid١'].map(
  (n) => `        ${k(n)} to ${hasRestrictedUsernamePrefix(n)},`,
)

const emails = [
  '', 'a@b.co', 'a@b.c', 'a@b', 'a.b@c.de', 'a..b@c.de', '.a@c.de', 'a.@c.de', 'a@c..de', 'a b@c.de', 'a@c.de ', ' a@c.de', '"a b"@c.de', '""@c.de',
  'a@[1.2.3.4]', 'a@[1.2.3]', 'a@[1234.1.1.1]', 'a@c-d.ef', 'a@-c.de', 'a@c.d1', 'a@c.de1', 'A@B.CO', 'a+b@c.de', "a'b@c.de", 'a@b@c.de', 'a<b@c.de',
  'a,b@c.de', 'a;b@c.de', 'a:b@c.de', 'a\\b@c.de', 'a(b)@c.de', 'a[b]@c.de', 'é@c.de', 'a@é.de', 'a@c.dé', 'a@sub.domain.example', 'a@c.de\n', 'a\n@c.de',
  'a@c.de ', 'a b@c.de', 'a\tb@c.de', 'user@example.com', 'first.last@mail.example.org', 'x@y.zz', 'a@1.2.co', 'a@c_d.de', '"a"b@c.de', '"a\nb"@c.de',
].map((e) => `        ${k(e)} to ${emailRe.test(e)},`)

const versions = ['', '4.0.0', '3.5.11', '3.5', '3', '10.20.30', 'v4.0.0', '4.0.0-beta', '4.x.1', '1.2.3.4', ' 4.1.2', '4. 1.2', '0.0.0', '3.999.999', '4.0.1000', 'abc', '4..2']
  .map((v) => `        ${k(v)} to ${parseVersionNumber(v)}L,`)

writeFileSync(out, `package com.ecency.core.app

/** Generated by native/tools/golden/generate-signup.mjs from the RN app's own sources. Do not edit. */
object SignupGoldens {
    /** name, RN getUsernameError (null: valid), RN isExchangeLikeUsername */
    val USERNAMES: List<Triple<String, String?, Boolean>> = listOf(
${usernameRows.join('\n')}
    )

    /** RN hasRestrictedUsernamePrefix */
    val RESTRICTED_PREFIX: List<Pair<String, Boolean>> = listOf(
${prefixRows.join('\n')}
    )

    /** RN registerScreen's email pattern */
    val EMAILS: List<Pair<String, Boolean>> = listOf(
${emails.join('\n')}
    )

    /** RN parseVersionNumber */
    val VERSIONS: List<Pair<String, Long>> = listOf(
${versions.join('\n')}
    )
}
`)
console.log(`wrote ${out}: ${usernameRows.length} usernames, ${emails.length} emails, ${versions.length} versions`)
