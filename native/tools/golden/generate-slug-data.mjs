// The transliteration tables of speakingurl (the package RN's generatePermlink slugs titles with), for the Kotlin port.
//
// Run from the RN app root (which has node_modules):
//   node native/tools/golden/generate-slug-data.mjs native/shared/src/commonMain/kotlin/com/ecency/core/editor/SlugData.kt
//
// Rerun when the app bumps speakingurl. Offline.
import { createRequire } from 'node:module'
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import vm from 'node:vm'

const out = process.argv[2]
if (!out) throw new Error('usage: generate-slug-data.mjs <output.kt>')
const require = createRequire(join(process.cwd(), 'package.json'))
const file = require.resolve('speakingurl/lib/speakingurl.js')
const version = require('speakingurl/package.json').version
// the tables are private to the module: run its source with one line added that hands them out
const src = readFileSync(file, 'utf8').replace(
  'var getSlug = function getSlug(',
  'root.__maps = { charMap: charMap, lookAheadCharArray: lookAheadCharArray, diatricMap: diatricMap, langCharMap: langCharMap, symbolMap: symbolMap };\n    var getSlug = function getSlug(',
)
const ctx = {}
vm.runInNewContext(src, ctx)
const m = ctx.__maps
if (!m) throw new Error('speakingurl layout changed')

const kStr = (s) => JSON.stringify(s).replace(/\$/g, '\\$')
// one "key<US>value" entry per line of a list, in chunks the JVM constant pool accepts
const table = (name, obj) => {
  const entries = Object.keys(obj).map((k) => `${k}\u001f${obj[k]}`)
  const chunks = []
  for (let i = 0; i < entries.length; i += 200) chunks.push(entries.slice(i, i + 200).join('\u001e'))
  return `    val ${name}: List<String> = listOf(\n${chunks.map((c) => `        ${kStr(c)},`).join('\n')}\n    )`
}

writeFileSync(out, `// GENERATED by native/tools/golden/generate-slug-data.mjs from speakingurl ${version}. Do not edit by hand.
package com.ecency.core.editor

/** speakingurl's tables: entries "key\\u001Fvalue" joined by \\u001E. English symbols and language characters only (getSlug's defaults). */
internal object SlugData {
    const val VERSION = ${kStr(version)}

${table('CHAR_MAP', m.charMap)}

${table('DIATRIC_MAP', m.diatricMap)}

${table('LANG_EN', m.langCharMap.en)}

${table('SYMBOL_EN', m.symbolMap.en)}

    const val LOOK_AHEAD = ${kStr(m.lookAheadCharArray.join(''))}
}
`)
console.log(`speakingurl ${version}: ${Object.keys(m.charMap).length} chars, ${Object.keys(m.diatricMap).length} diatrics`)
