// Golden vectors for the Kotlin port of RN's Listen helpers (src/utils/listen.ts, 760b9070be) in
// native/shared/src/commonMain/kotlin/com/ecency/core/app/Listen.kt. RN's own file runs here, unchanged.
//
// Run from the RN app root (node 22.6+ for --experimental-strip-types):
//   node --experimental-strip-types <native>/tools/golden/generate-listen.mjs \
//     <native>/shared/src/commonTest/kotlin/com/ecency/core/app/ListenGoldens.kt
//
// All text is synthetic (a seeded PRNG over a few scripts), nothing comes from real posts.
import { writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { pathToFileURL } from 'node:url'

const out = process.argv[2]
if (!out) throw new Error('usage: generate-listen.mjs <ListenGoldens.kt>')
const L = await import(pathToFileURL(join(process.cwd(), 'src/utils/listen.ts')).href)

function mulberry32(seed) {
  let a = seed >>> 0
  return () => {
    a = (a + 0x6d2b79f5) >>> 0
    let t = a
    t = Math.imul(t ^ (t >>> 15), t | 1)
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61)
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296
  }
}
const rnd = mulberry32(20261020)
const ri = (n) => Math.floor(rnd() * n)
const pick = (arr) => arr[ri(arr.length)]

// Kotlin string literal: every char outside printable ASCII escaped as \uXXXX (lone surrogates survive).
const kt = (s) =>
  '"' +
  Array.from({ length: s.length }, (_, i) => {
    const c = s.charCodeAt(i)
    if (c === 0x22) return '\\"'
    if (c === 0x5c) return '\\\\'
    if (c === 0x24) return '\\$'
    if (c >= 0x20 && c < 0x7f) return s[i]
    return '\\u' + c.toString(16).padStart(4, '0')
  }).join('') +
  '"'
const num = (x) => (Number.isNaN(x) ? 'Double.NaN' : x === Infinity ? 'Double.POSITIVE_INFINITY' : x === -Infinity ? 'Double.NEGATIVE_INFINITY' : Number.isInteger(x) ? `${x}.0` : `${x}`)

const times = [0, 0.4, 5, 59.9, 60, 61, 599.5, 3599, 3600, 7322.5, -1, -0.5, NaN, Infinity, 1e7]
const speeds = [...L.LISTEN_SPEEDS, 3, 0.5]
const trackSets = [[], ['en'], ['en', 'de'], ['de', 'en'], ['ja', 'en', 'ko']]
const uis = ['en-US', 'de-DE', 'de', 'ko-KR', 'fr-FR', '', 'pt-BR', 'en']
const secondsSets = [[], [0], [30], [150], [168], [287], [100, 100], [168, 287], [900, 60, 30], [29], [31], [149.9], [150.1]]
const words = [0, 1, 74, 75, 76, 150, 224, 225, 226, 1500]

// Scripts the bodies are made of: Latin, Cyrillic, Thai, Bengali (letters and vowel signs, which are \p{M}),
// Hebrew, Tamil, Telugu, Han, kana, hangul, Han outside the BMP, emoji, digits, punctuation, markup and links.
const pieces = [
  'Hello world ', 'reading on the train ', 'Привет мир ', 'สวัสดีครับ ', 'বাংলা ভাষা ', 'שלום עולם ', 'தமிழ் மொழி ',
  'తెలుగు భాష ', '你好世界 ', '中文的文章 ', 'こんにちは ', 'カタカナ ', '日本語の漢字 ', '안녕하세요 ', '한국어 ', '𠀀𠀁 ', '😀🎉 ',
  '12345 ', '!!! ... ', '[a link](https://example.com/x) ', '![img](https://images.example/a.png) ', 'https://example.com/path?q=1 ',
  '\ud800 ', '\udc00x ', 'é à ü ', 'ﬁ ',
]
const bodies = [
  '', '   ', 'Plain English text, nothing else.', 'สวัสดีครับ ทุกคน', 'שלום עולם', '你好世界，这是中文。', '日本語の漢字とひらがな',
  '漢字漢字漢字漢字漢字漢字漢字漢字 か', '안녕하세요 세계', 'Hello 你好世界你好世界', '[สวัสดี](https://x.y) English words here',
  'https://ไทย.example/สวัสดี and a few English words', '𠀀𠀁𠀂 ab', '😀😀😀', '12345 !!!', 'বাংলা ভাষা', 'ab\ud800cd',
  'தமிழ் English', 'తెలుగు', 'Привет мир',
]
for (let i = 0; i < 120; i++) {
  let s = ''
  const n = 1 + ri(8)
  for (let j = 0; j < n; j++) s += pick(pieces)
  bodies.push(s)
}

const lines = []
lines.push('package com.ecency.core.app')
lines.push('')
lines.push('// Generated by native/tools/golden/generate-listen.mjs from RN src/utils/listen.ts. Do not edit.')
lines.push('internal object ListenGoldens {')
lines.push('    val formatTime: List<Pair<Double, String>> = listOf(')
for (const t of times) lines.push(`        ${num(t)} to ${kt(L.formatTime(t))},`)
lines.push('    )')
lines.push('    val nextSpeed: List<Pair<Double, Double>> = listOf(')
for (const s of speeds) lines.push(`        ${num(s)} to ${num(L.nextSpeed(s))},`)
lines.push('    )')
lines.push('    /** tracks (languages), interface language, picked language (null: none). */')
lines.push('    val pickTrack: List<Triple<List<String>, String, String?>> = listOf(')
for (const set of trackSets) {
  for (const ui of uis) {
    const t = L.pickTrack(set.map((lang) => ({ lang, seconds: 1 })), ui)
    lines.push(`        Triple(listOf<String>(${set.map(kt).join(', ')}), ${kt(ui)}, ${t ? kt(t.lang) : 'null'}),`)
  }
}
lines.push('    )')
lines.push('    val preparingMinutes: List<Pair<List<Double>, Int>> = listOf(')
for (const set of secondsSets) lines.push(`        listOf<Double>(${set.map(num).join(', ')}) to ${L.preparingMinutes(set.map((seconds) => ({ seconds })))},`)
lines.push('    )')
lines.push('    /** seconds per language, words, minutes. */')
lines.push('    val listenMinutes: List<Triple<List<Double>, Int, Int>> = listOf(')
for (const set of secondsSets) {
  for (const w of words) {
    lines.push(`        Triple(listOf<Double>(${set.map(num).join(', ')}), ${w}, ${L.listenMinutes(set.map((seconds) => ({ seconds })), w)}),`)
  }
}
lines.push('    )')
lines.push('    val unreadable: List<Pair<String, Boolean>> = listOf(')
for (const b of bodies) lines.push(`        ${kt(b)} to ${L.isUnreadableScript(b)},`)
lines.push('    )')
lines.push('}')
lines.push('')
writeFileSync(out, lines.join('\n'))
console.log(`wrote ${out}: ${bodies.length} bodies`)
