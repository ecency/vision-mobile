// Golden vectors for a post with a 3Speak video: RN's own src/utils/editor.ts (extractVideoEmbedUrls,
// collectVideoThumbUrls, restoreVideoThumbs, extractMetadata with videoThumbUrls), run offline.
//
// Run from the RN app root (which has node_modules):
//   node --no-warnings native/tools/golden/generate-video-meta.mjs native/shared/src/commonTest/kotlin/com/ecency/core/editor/VideoMetaGoldenVectors.kt
import { register } from 'node:module'
import { writeFileSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const out = process.argv[2]
if (!out) throw new Error('usage: generate-video-meta.mjs <output.kt>')
register(pathToFileURL(join(dirname(fileURLToPath(import.meta.url)), 'rn-hooks.mjs')))
globalThis.__appVersion = '4.0.0'
const log = console.log
console.log = () => {}
const ed = await import(join(process.cwd(), 'src', 'utils/editor.ts'))

const kStr = (s) => JSON.stringify(s).replace(/\$/g, '\\$')
const kList = (a) => `listOf(${a.map(kStr).join(', ')})`
const embed = 'https://play.3speak.tv/embed?v=spike-voter/vid123'
const other = 'https://play.3speak.tv/embed?v=spike-voter/vid1234'
const thumb = 'https://images.ecency.com/DQmThumb/thumbnail.jpg'
const image = 'https://images.ecency.com/DQmImage/photo.png'
const bodies = [
  `Before.\n${embed}\n`,
  `Before.\n${embed}\n![](${image})\nAfter.`,
  `![](${image})\n\n${embed}\n\n![](${thumb})`,
  `Text with the longer address only\n${other}\n`,
  `${embed}\n\n${other}\n`,
  'No video here, just https://example.com/page and text.',
  `The embed in a link [watch](${embed}) and an image ![](${image})`,
  '',
]
const thumbSets = [[{ embedUrl: embed, thumbUrl: thumb }], [{ embedUrl: embed, thumbUrl: thumb }, { embedUrl: other, thumbUrl: image }], [{ embedUrl: '', thumbUrl: thumb }], []]
const cases = []
for (const body of bodies) {
  for (const videoThumbs of thumbSets) {
    const collected = ed.collectVideoThumbUrls({ videoThumbs, body })
    const meta = body ? await ed.extractMetadata({ body, thumbUrl: undefined, videoThumbUrls: collected, fetchRatios: false }) : {}
    const picked = body ? await ed.extractMetadata({ body, thumbUrl: collected[0], videoThumbUrls: collected, fetchRatios: false }) : {}
    cases.push(`        Case(${kStr(body)}, listOf(${videoThumbs.map((v) => `${kStr(v.embedUrl)} to ${kStr(v.thumbUrl)}`).join(', ')}), ${kList(ed.extractVideoEmbedUrls(body))}, ${kList(collected)}, ${kStr(JSON.stringify(meta))}, ${kStr(JSON.stringify(picked))}, listOf(${ed.restoreVideoThumbs(body, [thumb, image]).map((v) => `${kStr(v.embedUrl)} to ${kStr(v.thumbUrl)}`).join(', ')})),`)
  }
}
writeFileSync(out, `package com.ecency.core.editor

// Generated by native/tools/golden/generate-video-meta.mjs from RN's src/utils/editor.ts. Do not edit by hand.
internal object VideoMetaGoldenVectors {
    class Case(
        val body: String, val videoThumbs: List<Pair<String, String>>, val embeds: List<String>, val collected: List<String>,
        /** JSON.stringify(extractMetadata({body, videoThumbUrls: collected})) and the same with the first of them picked as thumbnail. */
        val meta: String, val metaWithThumb: String,
        /** restoreVideoThumbs(body, [thumb, image]). */
        val restored: List<Pair<String, String>>,
    )

    const val THUMB = ${kStr(thumb)}
    const val IMAGE = ${kStr(image)}

    val cases: List<Case> = listOf(
${cases.join('\n')}
    )
}
`)
log(`wrote ${cases.length} cases`)
