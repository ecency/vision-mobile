// Golden vectors for the compose translation: RN's own translateMarkdown.ts, translation.ts (chunkText, the emoji
// handling of getTranslation) and emojiStrip.ts run offline against a stand-in translator.
//
// Run from the RN app root (which has node_modules):
//   node --no-warnings native/tools/golden/generate-translate.mjs native/shared/src/commonTest/kotlin/com/ecency/core/editor/TranslateGoldenVectors.kt
//
// Nothing here talks to the translation service: every request is answered by `T(<text>)`.
import { register } from 'node:module'
import { writeFileSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const out = process.argv[2]
if (!out) throw new Error('usage: generate-translate.mjs <output.kt>')

register(pathToFileURL(join(dirname(fileURLToPath(import.meta.url)), 'rn-hooks.mjs')))
const log = console.log
console.log = () => {}

const rn = (p) => import(join(process.cwd(), 'src', p))
const { translateMarkdown } = await rn('providers/translation/translateMarkdown.ts')
const { chunkText } = await rn('providers/translation/translation.ts')
const { stripEmojis } = await rn('utils/emojiStrip.ts')

const kStr = (s) => JSON.stringify(s).replace(/\$/g, '\\$').replace(/[\u007f-\uffff]/g, (c) => '\\u' + c.charCodeAt(0).toString(16).padStart(4, '0'))
const kList = (a) => `listOf(${a.map(kStr).join(', ')})`

let sent = []
globalThis.__translate = async (path, body) => {
  if (path !== '/translate' || body.format !== 'text' || body.api_key !== '') throw new Error('unexpected request')
  sent.push(body.q)
  return { translatedText: `T(${body.q})` }
}

const long = (word, n) => Array.from({ length: n }, (_, i) => `${word}${i}`).join(' ')
const documents = [
  '',
  '   \n\n  ',
  'One paragraph.',
  'First paragraph.\n\nSecond paragraph.\n\n\n\nThird, after more blank lines.',
  'Windows line ends.\r\n\r\nSecond block.\rOld Mac line.',
  '# Heading\n\nText under it.\n\n## Second ###### not a marker\n####### seven hashes',
  '- one\n- two\n  continuation line\n- ![img](https://x.y/a.png)\n- https://example.com/only\n-\n- ',
  '1. first\n2. second\n10. tenth\n1.5 is a number\n3.no space',
  '> quoted\n> > nested quote\n>no space quote',
  'Before code\n```js\nconst a = 1\n\nconst b = 2\n```\nAfter code\n\n~~~\ntilde fence\n~~~~\nstill text?',
  '````\nlong fence\n```\nstill inside\n````\nout',
  '```\nnever closed\n\nstill code',
  '<div class="x">html block\nsecond line</div>\n\n  <center>indented html</center>\n\nText <b>inline</b> html.',
  '---\n\n***\n\n_ _ _\n\n- - -\ntext after rule\n\n--\n\n-*_',
  '![one](https://a.b/1.png)\n![two](https://a.b/2.png)\n\n![alt](https://a.b/3.png) with text\n\n![broken](https://a.b/4.png',
  'https://example.com/a\nhttp://example.com/b\n\nhttps://example.com/a and words\n\nhttps://\n\nhttps://a b',
  '| a | b |\n|---|---|\n| 1 | 2 |\n\na | b\n--- | ---\n\nprose with | a pipe\n- and a dash line\n\n| a | b | c |\n|---|---|\n\nx\n|-|',
  'Text with emoji \u{1F600} inside and \u{1F44D}\u{1F3FD} a thumb.\n\n\u{1F600}\u{1F600}\n\n- item \u2764\uFE0F heart\n- 1\uFE0F\u20E3 keycap\n\n\u{1F468}\u200D\u{1F469}\u200D\u{1F467} family \u2600 sun\n line two \u{1F600} \n end',
  '* star item\n+ plus item\n**bold** start\n*emphasis* start',
  '  indented paragraph\n\ttab line',
  `${long('word', 400)}`,
  `- ${long('item', 400)}\n- short`,
  `${'x'.repeat(3200)}`,
  `${long('alpha', 150)}\n\n${long('beta', 100)}\n\n${long('gamma', 100)}\n\nshort tail`,
  `${long('tail', 300)} \n\nafter`,
  'p1\n\n```\ncode\n```\n\np2\n\np3\n\n# h\n\np4',
  '#no space heading\n\n#\n\n# ',
  'mixed\n# heading inside block\nlast line',
  '\u00a0\u2028 odd spaces\u2029\n\n\ufeff',
]

const cases = []
for (const doc of documents) {
  sent = []
  const result = await translateMarkdown(doc, 'en', 'es')
  cases.push(`        Case(${kStr(doc)}, ${kList(sent)}, ${kStr(result)}),`)
}

const chunkInputs = [['a b c', 10], [long('w', 30), 20], ['abcdefghij klm', 4], ['  lead and trail  ', 6], ['one\n\ntwo\tthree ', 7], ['', 5], ['exactlyten', 10]]
const chunks = chunkInputs.map(([t, n]) => `        Chunks(${kStr(t)}, ${n}, ${kList(chunkText(t, n))}),`)

const emojiInputs = [
  'plain', '', '\u{1F600}', 'a \u{1F600} b', 'a\u{1F600}\n \u{1F600} b', '1\uFE0F\u20E3 #\u20E3 *\uFE0F\u20E3 9', 'x\uFE0F y', '\u2764\uFE0F \u2600 \u231A \u2B50',
  '\u{1F468}\u200D\u{1F469}\u200D\u{1F467}\u200D', '\u{1F44D}\u{1F3FD}\uFE0F ok', '\uD83D lone \uDE00', ' \u{1F600} \n \n x ', 'tab\t\u{1F600}\tend', '\u{1F1FA}\u{1F1F8} flag',
]
const emoji = emojiInputs.map((t) => { const r = stripEmojis(t); return `        Emoji(${kStr(t)}, ${kStr(r.clean)}, ${kStr(r.emojis)}),` })

writeFileSync(out, `package com.ecency.core.editor

// Generated by native/tools/golden/generate-translate.mjs from RN's translateMarkdown.ts, translation.ts and
// emojiStrip.ts with a stand-in translator that answers T(<text>). Do not edit by hand.
internal object TranslateGoldenVectors {
    class Case(val markdown: String, val requests: List<String>, val result: String)
    class Chunks(val text: String, val max: Int, val chunks: List<String>)
    class Emoji(val text: String, val clean: String, val emojis: String)

    val cases: List<Case> = listOf(
${cases.join('\n')}
    )

    val chunks: List<Chunks> = listOf(
${chunks.join('\n')}
    )

    val emoji: List<Emoji> = listOf(
${emoji.join('\n')}
    )
}
`)
log(`wrote ${cases.length} documents, ${chunks.length} chunk cases, ${emoji.length} emoji cases`)
