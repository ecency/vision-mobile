// Generates RN-app storage fixtures for the native key import, using the app's own src/utils/crypto.ts.
//
// Run from the RN app root (needs node_modules and src/):
//   node --experimental-strip-types --no-warnings native/tools/legacy/generate-fixtures.mjs \
//     native/shared/src/commonTest/kotlin/com/ecency/core/legacy/LegacyFixtures.kt
//
// PIN_KEY, DEFAULT_PIN, the PINs, passwords, tokens and keys below are dummies. Never use the real PIN_KEY here.
import { createRequire } from 'node:module'
import { writeFileSync } from 'node:fs'
import { join } from 'node:path'

const require = createRequire(join(process.cwd(), 'package.json'))
const { encryptKey } = await import(join(process.cwd(), 'src/utils/crypto.ts'))
const CryptoJS = require('crypto-js')
const { PrivateKey } = await import(require.resolve('@ecency/sdk'))

const out = process.argv[2]
if (!out) throw new Error('usage: generate-fixtures.mjs <output.kt>')

const PIN_KEY = 'spike-dummy-pin-key-not-real'
const PIN = '1357'
// The RN build's DEFAULT_PIN (fresh logins, migrated accounts) and an older user PIN kept in encUnlockPin.
const DEFAULT_PIN = '2468'
const UNLOCK_PIN = '9753'
const PASSWORD = 'P5DummyMasterPasswordForFixturesOnly'
const keys = Object.fromEntries(
  ['owner', 'active', 'posting', 'memo'].map((r) => [r, PrivateKey.fromLogin('spike-master', PASSWORD, r).toString()]),
)
const postingOnly = PrivateKey.fromSeed('spike-posting-dummy-seed').toString()
const enc = (v) => encryptKey(v, PIN)
const ownerOnly = PrivateKey.fromSeed('spike-owner-dummy-seed').toString()
const defaultPosting = PrivateKey.fromSeed('spike-default-dummy-seed').toString()

const users = [
  {
    username: 'spike-master', authType: 'masterKey', accessToken: enc('dummy-ecency-token'), hiveAuthExpiry: 0,
    masterKey: enc(PASSWORD), postingKey: enc(keys.posting), activeKey: enc(keys.active), memoKey: enc(keys.memo),
    ownerKey: enc(keys.owner), hiveAuthKey: '', hiveAuthToken: '',
  },
  {
    username: 'spike-posting', authType: 'postingKey', accessToken: enc('dummy-ecency-token-2'), hiveAuthExpiry: 0,
    masterKey: '', postingKey: enc(postingOnly), activeKey: '', memoKey: '', ownerKey: '', hiveAuthKey: '', hiveAuthToken: '',
  },
  {
    username: 'spike-signer', authType: 'steemConnect', accessToken: enc('dummy-hivesigner-access-token'), hiveAuthExpiry: 0,
    masterKey: '', postingKey: '', activeKey: '', memoKey: '', ownerKey: '', hiveAuthKey: '', hiveAuthToken: '',
  },
  {
    username: 'spike-has', authType: 'hiveAuth', accessToken: enc('dummy-ecency-token-3'), hiveAuthExpiry: 1791288000000,
    masterKey: '', postingKey: '', activeKey: '', memoKey: '', ownerKey: '',
    hiveAuthKey: enc('00000000-dummy-has-key'), hiveAuthToken: enc('dummy-has-token'),
  },
  {
    // Fresh login after the RN PIN migration: encrypted with DEFAULT_PIN, not the app PIN.
    username: 'spike-default', authType: 'postingKey', accessToken: encryptKey('dummy-ecency-token-4', DEFAULT_PIN),
    hiveAuthExpiry: 0, masterKey: '', postingKey: encryptKey(defaultPosting, DEFAULT_PIN), activeKey: '', memoKey: '',
    ownerKey: '', hiveAuthKey: '', hiveAuthToken: '',
  },
  {
    // updatePinCode skips ownerKey accounts, so this one still uses the user's old PIN (encUnlockPin).
    username: 'spike-owner', authType: 'ownerKey', accessToken: '', hiveAuthExpiry: 0, masterKey: '', postingKey: '',
    activeKey: '', memoKey: '', ownerKey: encryptKey(ownerOnly, UNLOCK_PIN), hiveAuthKey: '', hiveAuthToken: '',
  },
  {
    // Pre-stamp legacy encryption: decryptKey() rejects it, so the import must report it, not guess.
    username: 'spike-legacy', authType: 'postingKey', accessToken: '', hiveAuthExpiry: 0,
    masterKey: '', postingKey: CryptoJS.AES.encrypt(postingOnly, PIN).toString(), activeKey: '', memoKey: '',
    ownerKey: '', hiveAuthKey: '', hiveAuthToken: '',
  },
]

// redux-persist v6 stores each reducer as its own JSON string inside the root object.
const persistRoot = JSON.stringify({
  application: JSON.stringify({
    pin: encryptKey(PIN, PIN_KEY), encUnlockPin: encryptKey(UNLOCK_PIN, PIN_KEY), isPinCodeOpen: true, language: 'en-US',
  }),
  // The persisted account reducer keeps a `local` copy of the encrypted keys.
  account: JSON.stringify({
    currentAccount: { name: 'spike-posting', local: { postingKey: enc(postingOnly) } },
    otherAccounts: [{ name: 'spike-master', local: { postingKey: enc(keys.posting) } }],
  }),
  _persist: JSON.stringify({ version: 22, rehydrated: true }),
})

const k = (s) => JSON.stringify(s).replace(/\$/g, '\\$')
writeFileSync(out, `// GENERATED by native/tools/legacy/generate-fixtures.mjs with the RN app's src/utils/crypto.ts.
// Every secret here is a dummy: PIN_KEY, DEFAULT_PIN, PINs, password, tokens and keys control nothing.
package com.ecency.core.legacy

object LegacyFixtures {
    const val PIN_KEY = ${k(PIN_KEY)}
    const val PIN = ${k(PIN)}
    const val DEFAULT_PIN = ${k(DEFAULT_PIN)}
    const val UNLOCK_PIN = ${k(UNLOCK_PIN)}
    const val OWNER_ONLY = ${k(ownerOnly)}
    const val DEFAULT_POSTING = ${k(defaultPosting)}
    const val PASSWORD = ${k(PASSWORD)}
    const val OWNER = ${k(keys.owner)}
    const val ACTIVE = ${k(keys.active)}
    const val POSTING = ${k(keys.posting)}
    const val MEMO = ${k(keys.memo)}
    const val POSTING_ONLY = ${k(postingOnly)}

    /** AsyncStorage "persist:root". */
    const val PERSIST_ROOT = ${k(persistRoot)}

    /** AsyncStorage "user". */
    const val USERS = ${k(JSON.stringify(users))}

    /** One crypto-js passphrase ciphertext for the low-level decrypt test. */
    const val RAW_CIPHERTEXT = ${k(CryptoJS.AES.encrypt('crypto-js says hi', 'passphrase').toString())}
}
`)
console.log(`wrote ${users.length} accounts to ${out}`)
