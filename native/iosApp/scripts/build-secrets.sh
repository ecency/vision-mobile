#!/usr/bin/env bash
# Writes the build secrets (RN PIN_KEY and DEFAULT_PIN, and the optional user agent) into a gitignored Swift file at build time, so they
# never become Xcode build settings (which xcodebuild prints in its logs). Never echoes a value.
#
# Source: native/local.properties (untracked), the same keys the Android build reads:
#   ecency.pinKey=...        ecency.pinKeySha256=<sha-256 hex of the value>
#   ecency.defaultPin=...    ecency.defaultPinSha256=...
# Values are the raw text after the first '=' (trimmed, no escapes). CI writes that file from its secrets.
# Debug builds fall back to dummies. Any other configuration fails unless every value is set and matches
# its SHA-256, so a missing, truncated or wrong secret can never ship.
#
#   build-secrets.sh <output.swift>    (CONFIGURATION from Xcode, Debug when unset)
set -euo pipefail

OUT="${1:?output path required}"
NATIVE="$(cd "$(dirname "$0")/../.." && pwd)"
PROPS="$NATIVE/local.properties"
CONFIG="${CONFIGURATION:-Debug}"

prop() {
  [[ -f "$PROPS" ]] || return 0
  { grep -E "^[[:space:]]*$1[[:space:]]*=" "$PROPS" || true; } | head -1 | sed -E 's/^[^=]*=//; s/^[[:space:]]+//; s/[[:space:]]+$//'
}

bytes() { printf '%s' "$1" | od -An -v -tu1 | tr -s ' \n' ' ' | sed -E 's/^ //; s/ $//; s/ /, /g'; }

sha256() { printf '%s' "$1" | shasum -a 256 | cut -c1-64; }

secret() { # <name> <property> <debug dummy>
  local value sha
  value="$(prop "$2")"
  if [[ "$CONFIG" == "Debug" ]]; then
    printf '%s' "${value:-$3}"
    return
  fi
  sha="$(prop "$2Sha256" | tr 'A-F' 'a-f')"
  if [[ -z "$value" || -z "$sha" ]]; then
    echo "error: $1 or its SHA-256 is not set for this $CONFIG build. Put $2 and $2Sha256 in native/local.properties (see native/README.md, Secure storage)." >&2
    exit 1
  fi
  if [[ "$(sha256 "$value")" != "$sha" ]]; then
    echo "error: $1 does not match its SHA-256 (truncated or wrong value?)." >&2
    exit 1
  fi
  printf '%s' "$value"
}

pin_key="$(secret PIN_KEY ecency.pinKey debug-dummy-pin-key)"
default_pin="$(secret DEFAULT_PIN ecency.defaultPin 0000)"
# How this build names itself to Ecency's APIs (optional: empty means the shared core's generic default).
user_agent="$(prop ecency.userAgent)"
# RN ACTIVITY_WEBSOCKET_URL, the notification websocket used where push is unavailable (optional: empty means none).
activity_ws="$(prop ecency.activityWebsocketUrl)"
# RN ECENCY_BACKEND_API for chats (optional: empty means the Ecency host; only a first-party https host is used).
chat_backend="$(prop ecency.chatBackendUrl)"
# Where the update check looks (optional: empty means RN's repository and plain X.Y.Z tags).
update_url="$(prop ecency.updateReleasesUrl)"
update_prefix="$(prop ecency.updateTagPrefix)"
# Sentry (README "Crash reporting"): the DSN, a CI secret (optional: empty means no crash reporting).
sentry_dsn="$(prop ecency.sentryDsn)"
# Plausible (README "Analytics"): empty is RN's pl.ecency.com in Release and off in Debug, "off" turns it off.
plausible_host="$(prop ecency.plausibleHost)"

umask 077
mkdir -p "$(dirname "$OUT")"
tmp="$(mktemp "${OUT}.XXXXXX")"
cat > "$tmp" <<SWIFT
// GENERATED by iosApp/scripts/build-secrets.sh at build time. Gitignored: never commit this file.
enum GeneratedSecrets {
    static let pinKey: [UInt8] = [$(bytes "$pin_key")]
    static let defaultPin: [UInt8] = [$(bytes "$default_pin")]
    static let userAgent: [UInt8] = [$(bytes "$user_agent")]
    static let activityWebsocketUrl: [UInt8] = [$(bytes "$activity_ws")]
    static let chatBackendUrl: [UInt8] = [$(bytes "$chat_backend")]
    static let updateReleasesUrl: [UInt8] = [$(bytes "$update_url")]
    static let updateTagPrefix: [UInt8] = [$(bytes "$update_prefix")]
    static let sentryDsn: [UInt8] = [$(bytes "$sentry_dsn")]
    static let plausibleHost: [UInt8] = [$(bytes "$plausible_host")]
}
SWIFT
# Rewrite only on change, so unchanged secrets do not recompile the app.
if cmp -s "$tmp" "$OUT"; then rm -f "$tmp"; else mv -f "$tmp" "$OUT"; fi
