#!/usr/bin/env python3
"""Fetch the Material Symbols (Outlined, weight 400, 24px) the app uses and write them as Android vector drawables.

Reads icons.tsv next to this file. For every Material column it downloads the official SVG from the
google/material-design-icons repository (Apache 2.0, pinned to one commit) and writes
androidApp/src/main/res/drawable/ic_<icon>.xml (at rest) and ic_<icon>_fill.xml (the FILL 1 variant) when the
icon has one. Most SVGs have the viewBox "0 -960 960 960": the drawable keeps the 960 viewport and moves the
path down by 960 in a group, so the path data is the source's, untouched (a few older ones are 24 x 24, kept as
they are). Directional icons get android:autoMirrored.

Usage (from native/): python3 scripts/icons/material_symbols.py [--check]
  --check  fail when a drawable on disk differs from what the source gives (nothing is written).
"""
import os
import re
import sys
import urllib.request

COMMIT = "49d4db35df873165d6bd6ba09b063c7dafbac2f4"
BASE = f"https://raw.githubusercontent.com/google/material-design-icons/{COMMIT}/symbols/web"
HERE = os.path.dirname(os.path.abspath(__file__))
NATIVE = os.path.dirname(os.path.dirname(HERE))
OUT = os.path.join(NATIVE, "androidApp", "src", "main", "res", "drawable")
CACHE = os.path.join(HERE, ".cache")


def rows():
    with open(os.path.join(HERE, "icons.tsv"), encoding="utf-8") as f:
        for line in f:
            if line.startswith("#") or not line.strip():
                continue
            name, material, material_fill, _sf, _sf_fill, directional = line.rstrip("\n").split("\t")
            yield name, material, material_fill, directional == "yes"


def svg(symbol, filled):
    file = f"{symbol}_fill1_24px.svg" if filled else f"{symbol}_24px.svg"
    cached = os.path.join(CACHE, file)
    if os.path.exists(cached):
        with open(cached, encoding="utf-8") as f:
            return f.read()
    url = f"{BASE}/{symbol}/materialsymbolsoutlined/{file}"
    with urllib.request.urlopen(url, timeout=30) as r:
        body = r.read().decode("utf-8")
    os.makedirs(CACHE, exist_ok=True)
    with open(cached, "w", encoding="utf-8") as f:
        f.write(body)
    return body


def drawable(source, mirrored):
    box = re.search(r'viewBox="([^"]+)"', source)
    x, y, w, h = (float(v) for v in box.group(1).split()) if box else (0, 0, 24, 24)
    if x != 0 or w != h:
        raise ValueError("unexpected viewBox")
    size = f"{w:g}"
    shift = f' android:translateY="{-y:g}"' if y else ""
    paths = re.findall(r'<path d="([^"]+)"', source)
    if not paths:
        raise ValueError("no path")
    mirror = '\n    android:autoMirrored="true"' if mirrored else ""
    body = "".join(
        f'\n        <path\n            android:fillColor="#FF000000"\n            android:pathData="{d}" />' for d in paths
    )
    return (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        "<!-- Material Symbols Outlined (Apache 2.0), generated by scripts/icons/material_symbols.py -->\n"
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        '    android:width="24dp"\n'
        '    android:height="24dp"\n'
        f'    android:viewportWidth="{size}"\n'
        f'    android:viewportHeight="{size}"{mirror}>\n'
        f'    <group{shift}>{body}\n'
        "    </group>\n"
        "</vector>\n"
    )


def main():
    check = "--check" in sys.argv
    wanted = {}
    for name, material, material_fill, mirrored in rows():
        if material == "custom":
            continue
        base = "ic_" + name.lower()
        wanted[base] = drawable(svg(material, False), mirrored)
        if material_fill != "-":
            wanted[base + "_fill"] = drawable(svg(material if material_fill == "=" else material_fill, True), mirrored)
    stale = []
    for res, xml in sorted(wanted.items()):
        path = os.path.join(OUT, res + ".xml")
        current = open(path, encoding="utf-8").read() if os.path.exists(path) else None
        if current != xml:
            stale.append(res)
            if not check:
                with open(path, "w", encoding="utf-8") as f:
                    f.write(xml)
    if check and stale:
        print("out of date: " + ", ".join(stale))
        sys.exit(1)
    print(f"{len(wanted)} drawables" + (" checked" if check else f", {len(stale)} written"))


if __name__ == "__main__":
    main()
