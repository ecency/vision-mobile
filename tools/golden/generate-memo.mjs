// Golden vectors for encrypted transfer memos (hive/Memo.kt, #3633): a memo starting with `#` is encrypted with the
// sender's memo key for the recipient's memo public key, the format every Hive wallet reads.
// - the encoded memo from @ecency/sdk's Memo.encode (hive-tx), with a fixed nonce;
// - the same from @hiveio/dhive's Memo.encode, which must agree byte for byte;
// - each decodes back to the memo with the recipient's key (and the sender's).
//
//   npm ci --prefix tools
//   node tools/golden/generate-memo.mjs shared/src/commonTest/kotlin/com/ecency/core/hive/MemoGoldenVectors.kt
//
// Every key derives from a public throwaway seed and controls no funds. No network.
import { createRequire } from 'node:module'
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const require = createRequire(join(here, '..', 'package.json'))
const sdk = await import(require.resolve('@ecency/sdk'))
const dhive = require('@hiveio/dhive')

const out = process.argv[2]
if (!out) throw new Error('usage: generate-memo.mjs <output.kt>')
const version = (pkg) => JSON.parse(readFileSync(join(here, '..', 'node_modules', pkg, 'package.json'), 'utf8')).version

const seed = (n) => `ecency-native-memo-golden-throwaway-${n}`
const cases = [
  { from: 1, to: 2, nonce: '1', memo: '#hello' },
  { from: 1, to: 2, nonce: '1234567890123456789', memo: '#deposit 104857' },
  { from: 2, to: 1, nonce: '42', memo: '#Привет, 👋 مرحبا' },
  { from: 3, to: 4, nonce: '9000000000000000000', memo: '#' + 'long memo text '.repeat(14) },
  { from: 3, to: 4, nonce: '7', memo: '#' },
]

const kt = (s) => JSON.stringify(s).replace(/\$/g, '\\$')
const rows = cases.map((c) => {
  const a = sdk.PrivateKey.fromSeed(seed(c.from)), b = sdk.PrivateKey.fromSeed(seed(c.to))
  const encoded = sdk.Memo.encode(a.toString(), b.createPublic().toString(), c.memo, c.nonce)
  const viaDhive = dhive.Memo.encode(dhive.PrivateKey.fromSeed(seed(c.from)), dhive.PrivateKey.fromSeed(seed(c.to)).createPublic(), c.memo, c.nonce)
  if (encoded !== viaDhive) throw new Error(`sdk and dhive disagree on ${JSON.stringify(c)}`)
  for (const k of [b, a]) {
    const back = sdk.Memo.decode(k.toString(), encoded)
    if (back !== c.memo) throw new Error(`decode mismatch for ${JSON.stringify(c)}: ${back}`)
  }
  return `    MemoVector(${kt(seed(c.from))}, ${kt(seed(c.to))}, ${c.nonce}L, ${kt(c.memo)}, ${kt(encoded)}),`
})

writeFileSync(out, `package com.ecency.core.hive

// Generated by tools/golden/generate-memo.mjs from @ecency/sdk ${version('@ecency/sdk')} and @hiveio/dhive ${version('@hiveio/dhive')}. Do not edit.
// Throwaway seeds only; no key here controls funds.

internal class MemoVector(val fromSeed: String, val toSeed: String, val nonce: Long, val memo: String, val encoded: String)

internal val MEMO_VECTORS = listOf(
${rows.join('\n')}
)
`)
console.log(`wrote ${rows.length} vectors to ${out}`)
