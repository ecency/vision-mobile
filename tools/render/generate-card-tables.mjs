// The character table of render-helper's card image scan (card-image.ts autolinkWordChar, 2.5.55 #2157): which UTF-16
// code units Autolinker reads as word characters there, as V8 evaluates the two regexes card-image.ts tests a single
// code unit with (`/[\p{L}\p{Nd}\p{M}]/u` and its emoji class without the u flag). Read from the installed
// @ecency/render-helper bundle itself, so the table follows the oracle's regexes and V8's Unicode data. JS never runs
// in the app; this only runs offline.
//
//   cd tools/render && npm ci
//   node generate-card-tables.mjs ../../shared/src/commonMain/kotlin/com/ecency/core/render/CardAutolinkTable.kt
import { readFileSync, writeFileSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const out = process.argv[2]
if (!out) throw new Error('usage: generate-card-tables.mjs <output.kt>')
const pkg = JSON.parse(readFileSync(join(here, 'node_modules/@ecency/render-helper/package.json'), 'utf8'))
const bundle = readFileSync(join(here, 'node_modules/@ecency/render-helper/dist/node/index.mjs'), 'utf8')
const literal = (name) => {
  const m = new RegExp(`^var ${name} = (/.*/[a-z]*);$`, 'm').exec(bundle)
  if (!m) throw new Error(`${name} not found in the bundle`)
  return new Function(`return ${m[1]}`)()
}
const alnum = literal('AUTOLINK_ALNUM')
const emoji = literal('AUTOLINK_EMOJI')
const ranges = []
let start = -1
for (let c = 0; c <= 0x10000; c++) {
  const s = c < 0x10000 ? String.fromCharCode(c) : ''
  const on = c < 0x10000 && (alnum.test(s) || emoji.test(s))
  if (on && start < 0) start = c
  if (!on && start >= 0) {
    ranges.push(`${start.toString(16)}-${(c - 1).toString(16)}`)
    start = -1
  }
}
const lines = []
for (let i = 0; i < ranges.length; i += 12) lines.push(`        "${ranges.slice(i, i + 12).join(',')}${i + 12 < ranges.length ? ',' : ''}",`)
writeFileSync(out, `// GENERATED by tools/render/generate-card-tables.mjs from @ecency/render-helper ${pkg.version} (card-image.ts AUTOLINK_ALNUM, AUTOLINK_EMOJI) on Node ${process.versions.node}. Do not edit by hand.
package com.ecency.core.render

/** card-image.ts \`autolinkWordChar\`: the UTF-16 code units it reads as Autolinker word characters, as code unit ranges. */
internal object CardAutolinkTable {
    val WORD_CHARS: String = listOf(
${lines.join('\n')}
    ).joinToString("")
}
`)
console.log(`${ranges.length} ranges`)
