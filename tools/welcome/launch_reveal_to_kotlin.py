#!/usr/bin/env python3
"""Convert RN's welcome launch animation (a Lottie file) into Kotlin path data for LaunchReveal.

RN's welcome screen (src/screens/welcome) covers itself for 3.55 s with src/screens/launch: a Lottie animation
(animation-light.json / animation-dark.json, which differ only in an invisible fill) that draws the Ecency mark
with three strokes. This reads the shapes RN's file holds, applies each layer's transform (anchor, scale, position)
and writes them in the 500 x 500 composition's coordinates as cubic paths: a start point, then six numbers per
segment (both control points and the end point). Timing and widths live in LaunchReveal.kt.

Usage (from the repository root):
  git show rn-3.x-final:src/screens/launch/screen/animation-light.json > /tmp/launch.json
  python3 tools/welcome/launch_reveal_to_kotlin.py /tmp/launch.json shared/src/commonMain/kotlin/com/ecency/core/app/LaunchRevealData.kt
"""
import json
import sys


def transform(layer):
    ks = layer["ks"]
    px, py = ks["p"]["k"][:2]
    ax, ay = ks["a"]["k"][:2]
    sx, sy = (v / 100 for v in ks["s"]["k"][:2])
    return lambda x, y: ((x - ax) * sx + px, (y - ay) * sy + py)


def cubic(shape, t):
    """Lottie vertices with in and out tangents (relative) -> [x0, y0, c1x, c1y, c2x, c2y, x, y, ...]."""
    v, i, o, closed = shape["v"], shape["i"], shape["o"], shape["c"]
    n = len(v)
    out = list(t(*v[0]))
    for k in range(n if closed else n - 1):
        a, b = k, (k + 1) % n
        out += t(v[a][0] + o[a][0], v[a][1] + o[a][1])
        out += t(v[b][0] + i[b][0], v[b][1] + i[b][1])
        out += t(*v[b])
    return out


def paths(layer):
    return [it["ks"]["k"] for group in layer["shapes"] for it in group.get("it", []) if it["ty"] == "sh"]


def kotlin(values):
    return "floatArrayOf(" + ", ".join(f"{v:.3f}f" for v in values) + ")"


def main(source, target):
    with open(source, encoding="utf-8") as f:
        layers = {layer["ind"]: layer for layer in json.load(f)["layers"]}
    logo = layers[6]  # the whole mark: the matte the outer sweep is drawn outside of
    t = transform(logo)
    mark = [cubic(p, t) for p in paths(logo)]
    upper = cubic(layers[1]["masksProperties"][0]["pt"]["k"], transform(layers[1]))
    lower = cubic(layers[3]["masksProperties"][0]["pt"]["k"], transform(layers[3]))
    sweep_outer = cubic(paths(layers[7])[0], transform(layers[7]))
    sweep_lower = cubic(paths(layers[4])[0], transform(layers[4]))
    sweep_upper = cubic(paths(layers[2])[0], transform(layers[2]))
    with open(target, "w", encoding="utf-8") as f:
        f.write(
            "// Generated by tools/welcome/launch_reveal_to_kotlin.py from RN's src/screens/launch/screen/animation-light.json\n"
            "// (rn-3.x-final). Do not edit by hand.\n"
            "package com.ecency.core.app\n\n"
            "/** RN's launch animation shapes in its 500 x 500 composition: start point, then (c1, c2, end) per cubic. */\n"
            "object LaunchRevealData {\n"
            "    /** The Ecency mark: its inner and outer outlines, filled nonzero (the inner one is a hole). */\n"
            f"    val MARK: List<FloatArray> = listOf(\n        {kotlin(mark[0])},\n        {kotlin(mark[1])},\n    )\n\n"
            "    /** The part of the mark the upper sweep shows (closed). */\n"
            f"    val UPPER_AREA = {kotlin(upper)}\n\n"
            "    /** The part of the mark the lower sweep shows (closed). */\n"
            f"    val LOWER_AREA = {kotlin(lower)}\n\n"
            "    /** The wide sweep drawn around the mark, outside it (open). */\n"
            f"    val OUTER_SWEEP = {kotlin(sweep_outer)}\n\n"
            "    /** The sweep that fills the lower area of the mark (open). */\n"
            f"    val LOWER_SWEEP = {kotlin(sweep_lower)}\n\n"
            "    /** The sweep that fills the upper area of the mark (open). */\n"
            f"    val UPPER_SWEEP = {kotlin(sweep_upper)}\n"
            "}\n"
        )


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
