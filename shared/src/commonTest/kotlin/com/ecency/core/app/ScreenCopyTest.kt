    @Test
    fun screenCopyFollowsALiveLanguageSwitch() {
        texts.forEach { (_, read) -> read() }
        PseudoLocales.install(PseudoLocales.ACCENTED)
        // brand names stay as they are
        val english = Regex("[A-Za-z]{2,}")
        val brands = Regex("Ecency|HiveSigner|HiveAuth|Hivesigner|Keychain|Hive|PIN|NSFW|AI|MB|HP|URL|QR")
        val stale = texts.mapNotNull { (name, read) -> read().replace(brands, "").let { t -> "$name: $t".takeIf { english.containsMatchIn(t) } } }
        assertTrue(stale.isEmpty(), "English after the switch:\n" + stale.joinToString("\n"))
    }

